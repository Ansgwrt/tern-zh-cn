# ── 渲染：变量表 + 无 :has 的元素规则 ─────────────────────────────────
#
# 三条硬约束，都是实测出来的：
#   1. 选择器含 :has() 的规则会失去索引，每帧对每个元素各试一次。
#      键盘页 1.7–2.6 万元素，994 条带 :has() 的规则 → 样式计算 2.3 秒（首测 9.8 秒），卡死。
#      → 只有「变量表」带 :has()，正文规则一律不带。
#   2. 自定义属性会被子树里每个元素继承：键盘页 452 行 × 2 个变量在 .pf.sheet 上声明，
#      等于 2.6 万 × 900 次继承，又回到 945ms。
#      → 行数多的页面（键盘）把变量声明下沉到各自的 section 上，继承只在那一节内发生。
#   3. 清单 styles 合计不能超过 256 KiB（实测报错 styles are larger than 256 KiB）。
#      → 正文按节嵌套归组，选择器前缀只写一次。

NUDGE = "padding-top: 1px; margin-bottom: -1px;"
HARD = "letter-spacing: 0;"
SIZES = {"t": "13px", "h": "12px", "g": "12.5px", "b": "12px"}
BIG_PAGE = 40  # 行数超过这个的页面，变量下沉到 section


def scope(page):
    g, r = page
    return ".pf.sheet:has(.pf-group:nth-of-type(%d) .nav-row:nth-of-type(%d).on)" % (g, r)


def norm(kind):
    if kind.startswith("seg"):
        return "g", kind[3:]
    if kind.startswith("btn"):
        return "b", kind[3:]
    return kind, "0"


def vname(kind, sec, div, n):
    base = "--z%s-%d-%d" % (kind, sec, div)
    return base if n == "0" else base + "-" + n


def hide_name(name):
    return name.replace("--z", "--h", 1)


def leaf(kind, div, n):
    d = "div:nth-of-type(%d)" % div
    if kind == "t":
        return "& > " + d + " > .pf-lbl > .t"
    if kind == "h":
        return "& > " + d + " > .pf-lbl > .h"
    if kind == "g":
        return "& > " + d + " > .pf-ctl .pf-seg > button:nth-of-type(%s)" % n
    return "& > " + d + " > .pf-ctl .btn:nth-of-type(%s)" % n


keys = set()
per_page = {}
for page, rows in BODY.items():
    per_page[page] = {}
    for sec, div, kind, zh in rows:
        k, n = norm(kind)
        keys.add((k, sec, div, n))
        per_page[page].setdefault(sec, []).append((k, div, n, zh))

