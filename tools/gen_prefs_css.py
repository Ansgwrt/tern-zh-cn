    "\n/* ══ 设置 · 正文（变量表方案）═════════════════════════════════════\n"
    " * 变量表带 :has()，正文规则不带；行数多的页面把变量下沉到 section，避免整页继承。\n"
    " * 没翻译的页面没有这些变量 → 回落到原字号、内容为空，英文原样显示。\n"
    " */\n"
